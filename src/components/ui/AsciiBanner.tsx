export function AsciiBanner() {
  const [selectedIdx, setSelectedIdx] = useState(0);

  const nextVariant = () => {
    setSelectedIdx((prev) => (prev + 1) % asciiVariants.length);
  };

  return (
    <div
      className="select-none cursor-pointer overflow-hidden no-scrollbar"
      onClick={nextVariant}
      title="Click to toggle"
    >
      <pre
        className="font-mono text-[9px] sm:text-[11px] md:text-xs leading-[1.12] text-zinc-400 hover:text-zinc-200 transition-colors duration-200 overflow-hidden no-scrollbar whitespace-pre font-bold"
        aria-label="Ayush Yadav ASCII art"
      >
        {asciiVariants[selectedIdx]}
      </pre>
    </div>
  );
}
